test('a prompt becomes a pattern in the player', async ({ page }) => {
    const { chatRequests } = await mockNetwork(page, { reply: `Here you go:\n\`\`\`js\n${CODE}\n\`\`\``, model: 'x-ai/grok-4.7' });
    await seedStorage(page, { openrouter_api_key: 'sk-or-v1-test' });
    await page.goto('./');

    await page.getByRole('button', { name: 'acid techno bass' }).click(); // a chip fills the box, it does not send
    expect(chatRequests).toHaveLength(0);
    await expect(page.getByLabel('Message', { exact: true })).toHaveValue('acid techno bass');
    await page.keyboard.press('Enter');
    await expect(page.getByRole('button', { name: 'Send' })).toBeVisible();

    expect(chatRequests).toHaveLength(1);
    const { body, headers } = chatRequests[0];
    expect(body.stream).toBe(true);
    expect(body.messages.map((m) => m.role)).toEqual(['system', 'user']); // the user message is sent exactly once
    expect(body.messages[1].content).toBe('acid techno bass');
    expect(headers.authorization).toBe('Bearer sk-or-v1-test');

    // the player: strudel.cc with the code (and attribution) in the URL fragment
    const src = await page.locator('iframe').getAttribute('src');
    expect(src.startsWith('https://strudel.cc/#')).toBe(true);
    expect(decodeStrudelSrc(src)).toBe(`// Generated by x-ai/grok-4.7 via https://ronnqvist.github.io/strudel-vibe-coder/\n${CODE}`);
    await expect(page.locator('iframe')).toHaveAttribute('referrerpolicy', 'no-referrer');
    await expect(page.locator('iframe')).not.toHaveAttribute('allow', /.+/);
    await expect(page.getByText('x-ai/grok-4.7', { exact: true })).toBeVisible();
    await expect(page.getByRole('status')).toHaveText(/Reply received/);
});

