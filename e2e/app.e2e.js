test.describe('each chat has its own pattern (#7)', () => {
    const twoChats = {
        openrouter_api_key: 'sk-or-v1-test',
        openrouter_current_code: '$: s("hh*8")',
        openrouter_chats: JSON.stringify([
            { id: 'a', name: 'A', createdAt: '2026-01-01T00:00:00Z', messages: [] },
            { id: 'b', name: 'B', createdAt: '2026-01-01T00:00:00Z', messages: [] },
        ]),
        openrouter_current_chat_id: 'a',
    };
    const stage = async (page) => decodeStrudelSrc(await page.locator('iframe').getAttribute('src'));
    const openChat = async (page, name) => {
        await page.getByRole('button', { name: 'Chats', exact: true }).click();
        await page.getByRole('button', { name: new RegExp(`^${name}\\b`) }).first().click();
    };

    test('a reply that finishes in another chat leaves the viewed chat\'s stage alone', async ({ page }) => {
        await mockNetwork(page);
        await delayedReply(page, '```js\ns("bd")\n```', { ms: 1500 });
        await seedStorage(page, twoChats);
        await page.goto('./');
        expect(await stage(page)).toBe('$: s("hh*8")'); // the earlier global pattern is now chat A's

        await page.getByLabel('Message', { exact: true }).fill('beat');
        await page.keyboard.press('Enter');
        await openChat(page, 'B');
        expect(await stage(page)).toBe('');

        // B is not blocked by A's request
        await expect(page.getByLabel('Message', { exact: true })).toBeEnabled();
        await expect(page.getByRole('button', { name: 'Stop generating' })).toHaveCount(0);
        await expect(page.getByText('Generating vibe...')).toHaveCount(0);

        await expect(page.getByRole('status')).toHaveText(/A reply finished in the chat "A"/, { timeout: 5000 });
        expect(await stage(page)).toBe(''); // B's stage did not change
        await page.getByRole('button', { name: 'Chats', exact: true }).click();
        await expect(page.getByRole('button', { name: /^A \(new pattern\)/ })).toBeVisible();
        await page.getByRole('button', { name: /^A/ }).first().click();
        expect(await stage(page)).toBe('// Generated by mock-model via https://ronnqvist.github.io/strudel-vibe-coder/\ns("bd")');

        // "Restore previous" goes back to the pattern A had before
        await page.getByRole('button', { name: 'Restore previous' }).click();
        expect(await stage(page)).toBe('$: s("hh*8")');
        expect(await page.evaluate(() => localStorage.getItem('openrouter_current_code'))).toBe('$: s("hh*8")');
    });

    test('Stop cancels only the request of the chat being viewed', async ({ page }) => {
        await mockNetwork(page);
        const counter = await delayedReply(page, '```js\ns("bd")\n```', { ms: 2500 });
        await seedStorage(page, twoChats);
        await page.goto('./');
        await page.getByLabel('Message', { exact: true }).fill('in A');
        await page.keyboard.press('Enter');
        await openChat(page, 'B');
        await page.getByLabel('Message', { exact: true }).fill('in B');
        await page.keyboard.press('Enter');
        await expect.poll(() => counter.requests).toBe(2);
        await page.getByRole('button', { name: 'Stop generating' }).click(); // B's request
        await expect(page.getByRole('status')).toHaveText('Generation stopped');

        await expect(page.getByRole('status')).toHaveText(/A reply finished in the chat "A"/, { timeout: 6000 });
        const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('openrouter_chats')));
        expect(saved.find(c => c.id === 'a').messages.map(m => m.role)).toEqual(['user', 'assistant']);
        expect(saved.find(c => c.id === 'b').messages.map(m => m.role)).toEqual(['user']);
    });

    test('a revision request tells the model which pattern is on this chat\'s stage', async ({ page }) => {
        const { chatRequests } = await mockNetwork(page);
        await seedStorage(page, twoChats);
        await page.goto('./');
        await page.getByLabel('Message', { exact: true }).fill('make it slower');
        await page.keyboard.press('Enter');
        await expect(page.getByRole('status')).toHaveText(/Reply received/);
        const last = chatRequests[0].body.messages.at(-1);
        expect(last.role).toBe('user');
        expect(last.content).toContain('```js\n$: s("hh*8")\n```');
        expect(last.content.endsWith('My request:\nmake it slower')).toBe(true);
        // the chat keeps what the user typed
        const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('openrouter_chats')));
        expect(saved.find(c => c.id === 'a').messages[0].content).toBe('make it slower');
    });
});

