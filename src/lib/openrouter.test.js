import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { generateStrudelCode } from './openrouter';

const enc = new TextEncoder();
const sseChunk = (obj) => `data: ${typeof obj === 'string' ? obj : JSON.stringify(obj)}\n\n`;
const delta = (text, extra = {}) => sseChunk({ model: 'vendor/resolved-1', choices: [{ delta: { content: text } }], ...extra });

function sseResponse(parts, { split = false } = {}) {
    const bytes = enc.encode(parts.join(''));
    const chunks = split ? [bytes.slice(0, 7), bytes.slice(7, 40), bytes.slice(40)] : [bytes];
    return {
        ok: true,
        headers: { get: () => 'text/event-stream' },
        body: new ReadableStream({
            start(c) { chunks.forEach(b => c.enqueue(b)); c.close(); },
        }),
    };
}

function mockStream(parts, opts) {
    const fn = vi.fn(async () => sseResponse(parts, opts));
    vi.stubGlobal('fetch', fn);
    return fn;
}

const convo = [{ role: 'user', content: 'acid techno bass' }];

beforeEach(() => {
    vi.stubGlobal('window', {
        location: {
            origin: 'https://example.test',
            pathname: '/app/',
            href: 'https://example.test/app/?x=1#sk-or-v1-secretsecret',
        },
    });
});
afterEach(() => {
    vi.unstubAllGlobals();
    vi.restoreAllMocks();
});

describe('generateStrudelCode: request', () => {
    it('sends the system prompt and the conversation, each message once, with stream enabled', async () => {
        const fetchMock = mockStream([delta('hi'), 'data: [DONE]\n\n']);
        const conversation = [
            { role: 'user', content: 'acid techno bass' },
            { role: 'assistant', content: 'earlier answer' },
            { role: 'user', content: 'make it slower' },
        ];
        await generateStrudelCode('sk-or-v1-test', 'some/model', conversation, 'Some Model');

        const [, init] = fetchMock.mock.calls[0];
        const body = JSON.parse(init.body);
        expect(body.model).toBe('some/model');
        expect(body.stream).toBe(true);
        expect(body.messages[0].role).toBe('system');
        expect(body.messages.slice(1)).toEqual(conversation);
        expect(init.headers.Authorization).toBe('Bearer sk-or-v1-test');
    });

    it('requires an API key and does not call the network without one', async () => {
        const fetchMock = mockStream([]);
        await expect(generateStrudelCode('  ', 'm', convo)).rejects.toThrow('API Key is required');
        expect(fetchMock).not.toHaveBeenCalled();
    });

    it('identifies the app by origin and path only: never the URL hash or query', async () => {
        const fetchMock = mockStream([delta('x'), 'data: [DONE]\n\n']);
        await generateStrudelCode('k', 'm', convo, 'M');
        const referer = fetchMock.mock.calls[0][1].headers['HTTP-Referer'];
        expect(referer).toBe('https://example.test/app/');
        expect(referer).not.toContain('sk-or-v1');
    });

    it('passes the abort signal to fetch', async () => {
        const fetchMock = mockStream([delta('x'), 'data: [DONE]\n\n']);
        const controller = new AbortController();
        await generateStrudelCode('k', 'm', convo, 'M', { signal: controller.signal });
        expect(fetchMock.mock.calls[0][1].signal).toBe(controller.signal);
    });
});

describe('generateStrudelCode: streaming', () => {
    it('reports growing text, then returns reply, code with attribution, and the resolved model', async () => {
        mockStream([
            delta('Here:\n```js\n'),
            delta('s("bd'),
            delta(' sd")\n```'),
            sseChunk({ choices: [], usage: { total_tokens: 3 } }),
            'data: [DONE]\n\n',
        ], { split: true });
        const seen = [];
        const result = await generateStrudelCode('k', '~vendor/x-latest', convo, 'Model Name', { onText: t => seen.push(t) });

        expect(seen).toEqual(['Here:\n```js\n', 'Here:\n```js\ns("bd', 'Here:\n```js\ns("bd sd")\n```']);
        expect(result.content).toBe('Here:\n```js\ns("bd sd")\n```');
        // the model id is an alias; the attribution names the model that really answered
        expect(result.code).toContain('// Generated by vendor/resolved-1 via ');
        expect(result.modelLabel).toBe('vendor/resolved-1');
        expect(result.code).toContain('s("bd sd")');
        expect(result.resolvedModel).toBe('vendor/resolved-1');
        expect(result.stopped).toBe(false);
        expect(result.role).toBe('assistant');
    });

    it('marks a reply that ended at the length limit as truncated, and a normal one as not', async () => {
        mockStream([delta('```js\n$: s("bd*4")'), sseChunk({ choices: [{ delta: {}, finish_reason: 'length' }] }), 'data: [DONE]\n\n']);
        const cut = await generateStrudelCode('k', 'm', convo, 'M');
        expect(cut).toMatchObject({ truncated: true, stopped: false, content: '```js\n$: s("bd*4")' });

        mockStream([delta('```js\ns("bd")\n```'), sseChunk({ choices: [{ delta: {}, finish_reason: 'stop' }] }), 'data: [DONE]\n\n']);
        expect((await generateStrudelCode('k', 'm', convo, 'M')).truncated).toBe(false);
    });

    it('uses the display name when the model that answered is the one that was asked for', async () => {
        mockStream([sseChunk({ model: 'a/b', choices: [{ delta: { content: '```js\ns("bd")\n```' } }] }), 'data: [DONE]\n\n']);
        const result = await generateStrudelCode('k', 'a/b', convo, 'My Model');
        expect(result.modelLabel).toBe('My Model');
        expect(result.code).toContain('// Generated by My Model via ');
    });

    it('ignores keep-alive comments and malformed events', async () => {
        mockStream([': OPENROUTER PROCESSING\n\n', delta('a'), 'data: {not json\n\n', delta('b'), 'data: [DONE]\n\n']);
        expect((await generateStrudelCode('k', 'm', convo)).content).toBe('ab');
    });

    it('returns null code for a reply without a code block', async () => {
        mockStream([delta('Sure, what genre?'), 'data: [DONE]\n\n']);
        expect((await generateStrudelCode('k', 'm', convo)).code).toBeNull();
    });

    it('throws when the stream ends without any text', async () => {
        mockStream(['data: [DONE]\n\n']);
        vi.spyOn(console, 'error').mockImplementation(() => {});
        await expect(generateStrudelCode('k', 'm', convo)).rejects.toThrow('No response from model');
    });

    it('throws an error from inside the stream and keeps the partial text on the error', async () => {
        mockStream([delta('part'), sseChunk({ error: { message: 'Provider disconnected' }, choices: [{ delta: { content: '' }, finish_reason: 'error' }] })]);
        vi.spyOn(console, 'error').mockImplementation(() => {});
        const error = await generateStrudelCode('k', 'm', convo).catch(e => e);
        expect(error.message).toBe('Provider disconnected');
        expect(error.partial).toBe('part');
    });
});

describe('generateStrudelCode: stopping', () => {
    it('returns the text received so far with stopped: true instead of throwing', async () => {
        const controller = new AbortController();
        vi.stubGlobal('fetch', vi.fn(async (_url, init) => ({
            ok: true,
            headers: { get: () => 'text/event-stream' },
            body: new ReadableStream({
                start(c) {
                    c.enqueue(enc.encode(delta('```js\ns("bd")')));
                    init.signal.addEventListener('abort', () => c.error(new DOMException('Aborted', 'AbortError')));
                },
            }),
        })));

        const result = await generateStrudelCode('k', 'm', convo, 'M', {
            signal: controller.signal,
            onText: () => controller.abort(),
        });
        expect(result.stopped).toBe(true);
        expect(result.content).toBe('```js\ns("bd")');
        expect(result.code).toContain('s("bd")'); // an unterminated block still yields code
    });

    it('returns an empty reply, stopped, when aborted before any text arrived', async () => {
        const controller = new AbortController();
        controller.abort();
        vi.stubGlobal('fetch', vi.fn(async () => { throw new DOMException('Aborted', 'AbortError'); }));
        const result = await generateStrudelCode('k', 'm', convo, 'M', { signal: controller.signal });
        expect(result).toMatchObject({ content: '', code: null, stopped: true });
    });
});

describe('generateStrudelCode: other responses', () => {
    it('accepts a plain JSON reply when the provider ignores streaming', async () => {
        vi.stubGlobal('fetch', vi.fn(async () => ({
            ok: true,
            headers: { get: () => 'application/json' },
            json: async () => ({ model: 'vendor/json-1', choices: [{ message: { content: '```js\ns("hh*8")\n```' } }] }),
        })));
        const seen = [];
        const result = await generateStrudelCode('k', 'm', convo, 'M', { onText: t => seen.push(t) });
        expect(result.code).toContain('s("hh*8")');
        expect(result.resolvedModel).toBe('vendor/json-1');
        expect(seen).toEqual(['```js\ns("hh*8")\n```']);
    });

    it('surfaces the API error message for an HTTP error', async () => {
        vi.stubGlobal('fetch', vi.fn(async () => ({
            ok: false, status: 401, statusText: 'Unauthorized',
            json: async () => ({ error: { message: 'Invalid key' } }),
        })));
        vi.spyOn(console, 'error').mockImplementation(() => {});
        await expect(generateStrudelCode('k', 'm', convo)).rejects.toThrow('Invalid key');
    });

    it('falls back to the status line when the error body is not JSON', async () => {
        vi.stubGlobal('fetch', vi.fn(async () => ({
            ok: false, status: 502, statusText: 'Bad Gateway',
            json: async () => { throw new Error('not json'); },
        })));
        vi.spyOn(console, 'error').mockImplementation(() => {});
        await expect(generateStrudelCode('k', 'm', convo)).rejects.toThrow('OpenRouter API Error: 502 Bad Gateway');
    });
});

/**
 * How a reply ended (#5). Only `completed` may be loaded into the player automatically.
 * OpenRouter's documented signals (https://openrouter.ai/docs/api-reference/streaming,
 * https://openrouter.ai/docs/api-reference/errors): a terminal `finish_reason` on the last chunk,
 * then `data: [DONE]`; a mid-stream failure is a chunk with a top-level `error` and
 * `finish_reason: "error"`, still under HTTP 200.
 */
describe('generateStrudelCode: how the reply ended', () => {
    const done = 'data: [DONE]\n\n';
    const finish = (reason, extra = {}) => sseChunk({ choices: [{ delta: {}, finish_reason: reason, ...extra }] });
    const run = () => generateStrudelCode('k', 'm', convo, 'M');
    beforeEach(() => vi.spyOn(console, 'error').mockImplementation(() => {}));

    it('a stream that closes with no terminal signal is interrupted, not completed', async () => {
        mockStream([delta('Here:\n```js\ns("bd sd")')]);
        const result = await run();
        expect(result.status).toBe('interrupted');
        expect(result.content).toBe('Here:\n```js\ns("bd sd")');
    });

    it('finish_reason "stop" without [DONE] is completed', async () => {
        mockStream([delta('```js\ns("bd")\n```'), finish('stop')]);
        expect((await run()).status).toBe('completed');
    });

    it('[DONE] without any finish_reason is completed', async () => {
        mockStream([delta('```js\ns("bd")\n```'), done]);
        expect((await run()).status).toBe('completed');
    });

    it('finish_reason "length" is truncated', async () => {
        mockStream([delta('```js\ns("bd")'), finish('length'), done]);
        expect((await run())).toMatchObject({ status: 'truncated', finishReason: 'length' });
    });

    it('an empty reply that hit the length limit is truncated, not "no response"', async () => {
        mockStream([finish('length'), done]); // a reasoning model that spent its budget thinking
        expect((await run()).status).toBe('truncated');
    });

    it('finish_reason "content_filter" is refused', async () => {
        mockStream([delta('```js\ns("bd")\n```'), finish('content_filter'), done]);
        expect((await run()).status).toBe('refused');
    });

    it('a refusal delta is refused', async () => {
        mockStream([sseChunk({ choices: [{ delta: { refusal: 'I cannot help with that.' } }] }), finish('stop'), done]);
        const result = await run();
        expect(result.status).toBe('refused');
        expect(result.content).toContain('I cannot help with that.');
    });

    it('a mid-stream error chunk (HTTP 200) is error and keeps the partial text', async () => {
        mockStream([delta('part'), sseChunk({ error: { code: 502, message: 'Provider disconnected', metadata: { error_type: 'provider_unavailable' } }, choices: [{ delta: { content: '' }, finish_reason: 'error' }] })]);
        const result = await run();
        expect(result).toMatchObject({ status: 'error', content: 'part', error: { message: 'Provider disconnected', code: 502, type: 'provider_unavailable' } });
    });

    it('a stream whose only event is an error is error', async () => {
        mockStream([sseChunk({ error: { message: 'Rate limited' } })]);
        expect((await run())).toMatchObject({ status: 'error', content: '', error: { message: 'Rate limited' } });
    });

    it('finish_reason "error" without an error object is error', async () => {
        mockStream([delta('part'), finish('error'), done]);
        expect((await run()).status).toBe('error');
    });

    it('an unknown finish_reason still ends the reply as completed, and is recorded', async () => {
        mockStream([delta('```js\ns("bd")\n```'), finish('tool_calls', { native_finish_reason: 'tool_use' }), done]);
        expect((await run())).toMatchObject({ status: 'completed', finishReason: 'tool_calls', nativeFinishReason: 'tool_use' });
    });

    it('a stopped request is aborted and keeps the partial text', async () => {
        const controller = new AbortController();
        vi.stubGlobal('fetch', vi.fn(async (_url, init) => ({
            ok: true,
            headers: { get: () => 'text/event-stream' },
            body: new ReadableStream({
                start(c) {
                    c.enqueue(enc.encode(delta('```js\ns("bd")')));
                    init.signal.addEventListener('abort', () => c.error(new DOMException('Aborted', 'AbortError')));
                },
            }),
        })));
        const result = await generateStrudelCode('k', 'm', convo, 'M', { signal: controller.signal, onText: () => controller.abort() });
        expect(result).toMatchObject({ status: 'aborted', content: '```js\ns("bd")' });
    });

    it('a stream that ends with no text at all is error', async () => {
        mockStream([done]);
        expect((await run())).toMatchObject({ status: 'error', error: { message: 'No response from model' } });
    });

    it('records usage from the final chunk', async () => {
        mockStream([delta('x'), sseChunk({ choices: [{ delta: {}, finish_reason: 'stop' }], usage: { prompt_tokens: 5, completion_tokens: 1, total_tokens: 6, cost: 0.0001 } }), done]);
        expect((await run()).usage).toEqual({ prompt_tokens: 5, completion_tokens: 1, total_tokens: 6, cost: 0.0001 });
    });

    it('an HTTP error is error with the API message, not a thrown exception', async () => {
        vi.stubGlobal('fetch', vi.fn(async () => ({
            ok: false, status: 402, statusText: 'Payment Required',
            json: async () => ({ error: { code: 402, message: 'Insufficient credits' } }),
        })));
        expect((await run())).toMatchObject({ status: 'error', content: '', error: { message: 'Insufficient credits', code: 402 } });
    });

    it('a network failure is error, not a thrown exception', async () => {
        vi.stubGlobal('fetch', vi.fn(async () => { throw new TypeError('Failed to fetch'); }));
        expect((await run())).toMatchObject({ status: 'error', error: { message: 'Failed to fetch' } });
    });

    describe('JSON reply (provider ignored stream: true)', () => {
        const json = (body) => vi.stubGlobal('fetch', vi.fn(async () => ({ ok: true, headers: { get: () => 'application/json' }, json: async () => body })));
        const message = (content, finish_reason) => ({ choices: [{ message: { content }, finish_reason }] });

        it('a body without finish_reason is completed: a JSON body that parsed cannot have been cut off', async () => {
            json(message('```js\ns("bd")\n```'));
            expect((await run()).status).toBe('completed');
        });
        it('maps length, content_filter and error like the stream', async () => {
            json(message('```js\ns("bd")', 'length'));
            expect((await run()).status).toBe('truncated');
            json(message('no', 'content_filter'));
            expect((await run()).status).toBe('refused');
            json(message('', 'error'));
            expect((await run()).status).toBe('error');
        });
        it('a 200 body that is only an error object is error', async () => {
            json({ error: { code: 429, message: 'Rate limited' } });
            expect((await run())).toMatchObject({ status: 'error', error: { message: 'Rate limited', code: 429 } });
        });
        it('a message.refusal is refused', async () => {
            json({ choices: [{ message: { content: null, refusal: 'No.' }, finish_reason: 'stop' }] });
            expect((await run())).toMatchObject({ status: 'refused', content: 'No.' });
        });
    });
});
