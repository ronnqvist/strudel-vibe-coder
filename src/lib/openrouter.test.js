import { afterEach, describe, expect, it, vi } from 'vitest';
import { generateStrudelCode } from './openrouter';

function mockFetch(content = '```js\ns("bd sd")\n```') {
    const fn = vi.fn(async () => ({
        ok: true,
        json: async () => ({ choices: [{ message: { content } }] }),
    }));
    vi.stubGlobal('fetch', fn);
    vi.stubGlobal('window', { location: { href: 'https://example.test/app/' } });
    return fn;
}

afterEach(() => vi.unstubAllGlobals());

describe('generateStrudelCode', () => {
    it('sends the system prompt followed by the conversation, each message exactly once', async () => {
        const fetchMock = mockFetch();
        const conversation = [
            { role: 'user', content: 'acid techno bass' },
            { role: 'assistant', content: 'earlier answer' },
            { role: 'user', content: 'make it slower' },
        ];
        await generateStrudelCode('sk-or-v1-test', 'some/model', conversation, 'Some Model');

        const body = JSON.parse(fetchMock.mock.calls[0][1].body);
        expect(body.model).toBe('some/model');
        expect(body.messages[0].role).toBe('system');
        expect(body.messages.slice(1)).toEqual(conversation);
        expect(body.messages.filter(m => m.content === 'make it slower')).toHaveLength(1);
    });

    it('requires an API key and does not call the network without one', async () => {
        const fetchMock = mockFetch();
        await expect(generateStrudelCode('  ', 'm', [{ role: 'user', content: 'x' }])).rejects.toThrow('API Key is required');
        expect(fetchMock).not.toHaveBeenCalled();
    });

    it('returns the reply and the extracted code with an attribution line', async () => {
        mockFetch('Here you go\n```js\ns("bd sd")\n```');
        const result = await generateStrudelCode('k', 'm', [{ role: 'user', content: 'x' }], 'Model Name');
        expect(result.code).toContain('// Generated by Model Name via ');
        expect(result.code).toContain('s("bd sd")');
        expect(result.role).toBe('assistant');
    });

    it('surfaces the API error message', async () => {
        vi.stubGlobal('window', { location: { href: 'https://example.test/app/' } });
        vi.stubGlobal('fetch', vi.fn(async () => ({
            ok: false, status: 401, statusText: 'Unauthorized',
            json: async () => ({ error: { message: 'Invalid key' } }),
        })));
        vi.spyOn(console, 'error').mockImplementation(() => {});
        await expect(generateStrudelCode('k', 'm', [{ role: 'user', content: 'x' }])).rejects.toThrow('Invalid key');
    });
});
