import { describe, expect, it } from 'vitest';
import { codeFromMessage, extractCode, withAttribution } from './extractCode';
import { APP_URL } from '../config';

const fence = (lang, body) => '```' + lang + '\n' + body + '\n```';

describe('extractCode', () => {
    it('extracts a js block from surrounding prose', () => {
        expect(extractCode(`Here you go:\n${fence('js', 's("bd sd")')}\nEnjoy!`)).toBe('s("bd sd")');
    });

    it('accepts javascript, strudel and upper-case tags', () => {
        expect(extractCode(fence('javascript', 'a'))).toBe('a');
        expect(extractCode(fence('strudel', 'b'))).toBe('b');
        expect(extractCode(fence('JS', 'c'))).toBe('c');
    });

    it('accepts extra words after the language tag', () => {
        expect(extractCode('```js title="beat.js"\ns("bd")\n```')).toBe('s("bd")');
    });

    it('returns an empty string without a code block, even if the prose mentions s( or note(', () => {
        expect(extractCode('')).toBe('');
        expect(extractCode(undefined)).toBe('');
        expect(extractCode('You can use s("bd") or note("c e g") to start. await initHydra() adds visuals.')).toBe('');
    });

    it('ignores non-JavaScript blocks', () => {
        expect(extractCode(fence('bash', 'npm install'))).toBe('');
        expect(extractCode(`${fence('json', '{}')}\n${fence('js', 's("bd")')}`)).toBe('s("bd")');
    });

    it('uses an untagged block only when there is no tagged JavaScript block', () => {
        expect(extractCode(fence('', 's("bd")'))).toBe('s("bd")');
        expect(extractCode(`${fence('', 'untagged')}\n${fence('js', 'tagged')}`)).toBe('tagged');
    });

    it('takes the last of several similar-sized blocks (the updated version)', () => {
        const v1 = 'stack(\n  s("bd sd"),\n  note("c e g")\n)';
        const v2 = 'stack(\n  s("bd sd hh"),\n  note("c e g b")\n)';
        expect(extractCode(`Before:\n${fence('js', v1)}\nAfter:\n${fence('js', v2)}`)).toBe(v2);
    });

    it('ignores a short trailing snippet and keeps the main pattern', () => {
        const main = 'stack(\n  s("bd sd, hh*8"),\n  note("c2 eb2 g2").s("sawtooth").lpf(600),\n  note("<c4 e4>").s("piano")\n)';
        expect(extractCode(`${fence('js', main)}\nTo change the tempo:\n${fence('js', 'setcps(0.6)')}`)).toBe(main);
    });

    it('keeps an unterminated block (reply cut off by the token limit)', () => {
        expect(extractCode('Sure!\n```js\ns("bd sd")\nnote("c e g")')).toBe('s("bd sd")\nnote("c e g")');
    });

    it('handles Windows line endings', () => {
        expect(extractCode('```js\r\ns("bd")\r\n```\r\n')).toBe('s("bd")');
    });

    it('does not end a block at a longer fence inside it', () => {
        expect(extractCode('````js\nconst a = `\n```\n`;\n````')).toBe('const a = `\n```\n`;');
    });

    it('skips empty blocks', () => {
        expect(extractCode(`${fence('js', '   ')}\n${fence('js', 's("bd")')}`)).toBe('s("bd")');
    });
});

describe('withAttribution', () => {
    it('adds the attribution line once', () => {
        const once = withAttribution('s("bd")', 'Model X');
        expect(once).toBe(`// Generated by Model X via ${APP_URL}\ns("bd")`);
        expect(withAttribution(once, 'Model X')).toBe(once);
    });

    it('returns empty for empty code and the code itself when there is no model', () => {
        expect(withAttribution('', 'M')).toBe('');
        expect(withAttribution('s("bd")', undefined)).toBe('s("bd")');
    });
});

describe('codeFromMessage', () => {
    it('reads the message text (so edits count) and attributes the model that wrote it', () => {
        const msg = { role: 'assistant', model: 'Model X', content: `edited\n${fence('js', 's("hh*8")')}`, code: 'stale' };
        expect(codeFromMessage(msg)).toBe(`// Generated by Model X via ${APP_URL}\ns("hh*8")`);
    });

    it('yields an empty string when the message has no code', () => {
        expect(codeFromMessage({ role: 'assistant', content: 'just words' })).toBe('');
    });
});
