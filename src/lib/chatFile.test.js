import { describe, expect, it } from 'vitest';
import {
    CHAT_FILE_FORMAT,
    CHAT_FILE_VERSION,
    ChatFileError,
    buildExport,
    describeImport,
    exportFileName,
    parseChatFile,
} from './chatFile';

const NOW = new Date('2026-11-04T12:00:00.000Z');
let n = 0;
const opts = () => ({ now: NOW, makeId: () => `new-${++n}` });

// Shaped like what the app wrote before the format had a version.
const legacyChat = {
    id: 'abc123',
    name: 'acid techno bass',
    createdAt: '2025-11-27T10:00:00.000Z',
    messages: [
        { role: 'user', content: 'acid techno bass' },
        { role: 'assistant', content: 'Here:\n```js\ns("bd")\n```', code: '// Generated by Claude Opus 4.5 via https://ronnqvist.github.io/strudel-vibe-coder/\ns("bd")', model: 'Claude Opus 4.5' },
        { role: 'assistant', content: 'Error: Invalid key' },
        { role: 'assistant', content: 'no code here', code: null, model: 'GPT 5.1' },
    ],
};

describe('parseChatFile: files written by earlier versions', () => {
    it('imports a single exported chat', () => {
        const result = parseChatFile(JSON.stringify(legacyChat), opts());
        expect(result.version).toBe(1);
        expect(result.chats).toHaveLength(1);
        expect(result.chats[0]).toMatchObject({ name: 'acid techno bass', createdAt: '2025-11-27T10:00:00.000Z' });
        expect(result.chats[0].messages).toEqual(legacyChat.messages);
        expect(result.skippedChats + result.skippedMessages).toBe(0);
    });

    it('imports an "Export All" array and skips entries that are not chats', () => {
        const file = [legacyChat, { id: 'x', name: 'second', messages: [] }, { bogus: true }, 'text', null];
        const result = parseChatFile(JSON.stringify(file), opts());
        expect(result.chats.map(c => c.name)).toEqual(['acid techno bass', 'second']);
        expect(result.skippedChats).toBe(3);
    });

    it('always assigns fresh, distinct ids', () => {
        const result = parseChatFile(JSON.stringify([legacyChat, legacyChat]), opts());
        const ids = result.chats.map(c => c.id);
        expect(ids).not.toContain('abc123');
        expect(new Set(ids).size).toBe(2);
    });
});

describe('parseChatFile: current format', () => {
    it('round-trips through buildExport', () => {
        const chats = [legacyChat, { id: 'b', name: 'ambient', createdAt: '2025-11-26T10:00:00.000Z', messages: [{ role: 'user', content: 'ä ö å € 🎵' }] }];
        const file = buildExport(chats, NOW);
        expect(file).toMatchObject({ format: CHAT_FILE_FORMAT, version: CHAT_FILE_VERSION, exportedAt: '2026-11-04T12:00:00.000Z' });
        const result = parseChatFile(JSON.stringify(file), opts());
        expect(result.version).toBe(CHAT_FILE_VERSION);
        expect(result.chats.map(c => ({ name: c.name, messages: c.messages, createdAt: c.createdAt })))
            .toEqual(chats.map(c => ({ name: c.name, messages: c.messages, createdAt: c.createdAt })));
    });

    it('imports a file from a newer version, with a warning', () => {
        const file = { format: CHAT_FILE_FORMAT, version: 7, chats: [legacyChat], somethingNew: true };
        const result = parseChatFile(JSON.stringify(file), opts());
        expect(result.chats).toHaveLength(1);
        expect(result.warnings[0]).toMatch(/newer version/);
        expect(describeImport(result)).toMatch(/newer version/);
    });
});

describe('parseChatFile: cleaning', () => {
    it('keeps only the fields the app knows, in messages and chats', () => {
        const dirty = {
            id: 'x', name: 'n', createdAt: '2025-01-01T00:00:00.000Z', evil: '<script>', __proto__x: 1,
            messages: [{ role: 'user', content: 'hi', onclick: 'alert(1)', html: '<b>' }, { role: 'assistant', content: 'yo', stopped: true, truncated: true, model: 'M', code: 'c' }],
        };
        const { chats } = parseChatFile(JSON.stringify(dirty), opts());
        expect(Object.keys(chats[0]).sort()).toEqual(['createdAt', 'id', 'messages', 'name']);
        expect(chats[0].messages).toEqual([{ role: 'user', content: 'hi' }, { role: 'assistant', content: 'yo', code: 'c', model: 'M', stopped: true, truncated: true }]);
    });

    it('skips and counts messages with an unknown role or non-text content', () => {
        const chat = { name: 'n', messages: [
            { role: 'user', content: 'ok' }, { role: 'system', content: 'no' }, { role: 'user', content: 42 },
            { role: 'user' }, null, 'text', { role: 'assistant', content: 'also ok' },
        ] };
        const result = parseChatFile(JSON.stringify(chat), opts());
        expect(result.chats[0].messages.map(m => m.content)).toEqual(['ok', 'also ok']);
        expect(result.skippedMessages).toBe(5);
        expect(describeImport(result)).toBe('Imported 1 chat. Skipped 5 messages that could not be read.');
    });

    it('names unnamed chats and trims long names; repairs a missing or invalid date', () => {
        const long = 'x'.repeat(500);
        const result = parseChatFile(JSON.stringify([{ messages: [] }, { name: '   ', messages: [] }, { name: long, messages: [], createdAt: 'not a date' }]), opts());
        expect(result.chats[0].name).toMatch(/^Imported /);
        expect(result.chats[1].name).toMatch(/^Imported /);
        expect(result.chats[2].name).toHaveLength(200);
        expect(result.chats[2].createdAt).toBe('2026-11-04T12:00:00.000Z');
    });

    it('does not let a "__proto__" key in the file pollute anything', () => {
        parseChatFile('{"name":"n","messages":[],"__proto__":{"polluted":true}}', opts());
        expect({}.polluted).toBeUndefined();
    });
});

describe('parseChatFile: rejecting files', () => {
    it.each([
        ['not JSON', '{oops', /not valid JSON/],
        ['a number', '42', /does not look like/],
        ['an unrelated object', '{"hello":"world"}', /does not look like/],
        ['an empty array', '[]', /No chats found/],
        ['only invalid entries', '[1, null, {"a":1}]', /No chats found/],
        ['an envelope without chats', `{"format":"${CHAT_FILE_FORMAT}","version":2}`, /does not look like/],
    ])('%s', (_label, text, message) => {
        expect(() => parseChatFile(text, opts())).toThrow(ChatFileError);
        expect(() => parseChatFile(text, opts())).toThrow(message);
    });
});

describe('exportFileName / describeImport', () => {
    it('names a single-chat export after the chat, with a safe file name', () => {
        expect(exportFileName([{ name: 'acid techno bass' }])).toBe('strudel-chat-acid_techno_bass.json');
        expect(exportFileName([{ name: 'a/b\\c:d*?"<>|' }])).toBe('strudel-chat-a_b_c_d.json');
        expect(exportFileName([{ name: 'Låt: sång 🎵' }])).toBe('strudel-chat-Låt_sång.json');
        expect(exportFileName([{ name: '???' }])).toBe('strudel-chat-chat.json');
    });

    it('names an all-chats export after the date', () => {
        expect(exportFileName([{ name: 'a' }, { name: 'b' }], { all: true, now: NOW })).toBe('strudel-chats-backup-2026-11-04.json');
    });

    it('names "export all" as a backup even when there is only one chat', () => {
        expect(exportFileName([{ name: 'only' }], { all: true, now: NOW })).toBe('strudel-chats-backup-2026-11-04.json');
        expect(exportFileName([{ name: 'a' }, { name: 'b' }], { now: NOW })).toBe('strudel-chats-backup-2026-11-04.json');
    });

    it('describes a clean import and pluralises', () => {
        const base = { skippedChats: 0, skippedMessages: 0, warnings: [] };
        expect(describeImport({ ...base, chats: [{}] })).toBe('Imported 1 chat.');
        expect(describeImport({ ...base, chats: [{}, {}], skippedChats: 1 })).toBe('Imported 2 chats. Skipped 1 chat that could not be read.');
    });
});

describe('parseChatFile: format 3 (pattern revisions)', () => {
    const revisionChat = {
        id: 'a', name: 'with revisions', createdAt: '2026-11-05T10:00:00.000Z',
        messages: [
            { id: 'm1', role: 'user', content: 'beat' },
            { id: 'm2', role: 'assistant', content: '```js\ns("bd")\n```', code: 's("bd")', model: 'M', status: 'completed', finishReason: 'stop', usage: { total_tokens: 12, cost: 0.001, junk: 'x' }, revisionId: 'r1', promptVersion: '2.0.0' },
            { id: 'm3', role: 'assistant', content: 'part', model: 'M', status: 'interrupted', error: 'gone' },
        ],
        revisions: [
            { id: 'r1', code: 's("bd")', origin: 'reply', messageId: 'm2', model: 'M', createdAt: '2026-11-05T10:01:00.000Z' },
            { id: 'r2', code: 's("bd").gain(.5)', origin: 'edited', repaired: true, createdAt: '2026-11-05T10:02:00.000Z' },
        ],
        selectedRevisionId: 'r2',
        previousRevisionId: 'r1',
    };

    it('round-trips revisions, the selection, and the new message fields', () => {
        const { chats, version } = parseChatFile(JSON.stringify(buildExport([revisionChat], NOW)), opts());
        expect(version).toBe(3);
        const [c] = chats;
        expect(c.revisions).toEqual(revisionChat.revisions);
        expect(c.selectedRevisionId).toBe('r2');
        expect(c.previousRevisionId).toBe('r1');
        expect(c.messages[1]).toEqual({ ...revisionChat.messages[1], usage: { total_tokens: 12, cost: 0.001 } });
        expect(c.messages[2]).toMatchObject({ status: 'interrupted', error: 'gone' });
    });

    it('drops invalid revisions and a selection that points nowhere', () => {
        const bad = { ...revisionChat, revisions: [{ id: 'r1', code: 42, origin: 'reply' }, { id: '../x', code: 'c', origin: 'reply' }, { id: 'r3', code: 'c', origin: 'magic' }], selectedRevisionId: 'r1' };
        const [c] = parseChatFile(JSON.stringify(bad), opts()).chats;
        expect(c.revisions).toBeUndefined();
        expect(c.selectedRevisionId).toBeUndefined();
    });

    it('ignores an unknown status and an invalid message id', () => {
        const odd = { name: 'n', messages: [{ id: 'has space', role: 'assistant', content: 'x', status: 'weird' }] };
        const [c] = parseChatFile(JSON.stringify(odd), opts()).chats;
        expect(c.messages[0]).toEqual({ role: 'assistant', content: 'x' });
    });

    it('a version 2 file still imports, without revisions', () => {
        const v2 = { format: CHAT_FILE_FORMAT, version: 2, exportedAt: NOW.toISOString(), chats: [legacyChat] };
        const result = parseChatFile(JSON.stringify(v2), opts());
        expect(result.version).toBe(2);
        expect(result.warnings).toEqual([]);
        expect(result.chats[0].revisions).toBeUndefined();
    });
});
