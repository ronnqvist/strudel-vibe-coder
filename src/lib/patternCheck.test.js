import { describe, expect, it, vi } from 'vitest';
import { patternSyntaxError, preparePattern } from './patternCheck';

describe('patternSyntaxError', () => {
    it('accepts the forms Strudel code uses', async () => {
        const valid = [
            's("bd sd hh sd")',
            '$: s("bd*4")\n$: note("c2 g2").s("sawtooth")', // several $: labels
            'await initHydra()\nosc(10, 0.1, 1.2).out()\n$: s("bd sd")', // top-level await
            'await initHydra({detectAudio: true})\nlet pattern = "3 4 5 [6 7]*2"\nshape(H(pattern)).out(o0)\nnote(pattern).s("piano")',
            'setcpm(120/4)\nstack(\n  s("bd(3,8), sd(5,8)"),\n  note(`<[c3,e3,g3] [a2,c3,e3]>`).s("piano").room(0.5)\n)',
            '// Generated by Model X via https://ronnqvist.github.io/strudel-vibe-coder/\n// ä ö å € 🎵\ns("bd").every(4, x => x.fast(2))',
        ];
        for (const code of valid) expect(await patternSyntaxError(code), code).toBeNull();
    });

    it('refuses code that does not parse, with the parser message and position', async () => {
        expect(await patternSyntaxError('s("bd sd"')).toMatch(/Unexpected token \(1:9\)/);
        expect(await patternSyntaxError('stack(\n  s("bd"),\n  note("c e g"))\n)')).toMatch(/\(4:0\)/);
        expect(await patternSyntaxError('s(“bd”)')).toMatch(/Unexpected character/); // smart quotes
    });

    it('lets empty input through (nothing to load)', async () => {
        expect(await patternSyntaxError('')).toBeNull();
        expect(await patternSyntaxError('   \n')).toBeNull();
        expect(await patternSyntaxError(undefined)).toBeNull();
    });

    it('fails closed when the parser breaks in a way that is not a syntax error (review G1)', async () => {
        const broken = () => { throw new TypeError('parser bug'); };
        expect(await patternSyntaxError('s("bd")', { parse: broken })).toMatch(/could not be checked/);
    });

    it('fails closed when the parser cannot be loaded, and tries to load it again next time (review G1)', async () => {
        const load = vi.fn().mockRejectedValueOnce(new TypeError('Failed to fetch dynamically imported module'))
            .mockResolvedValueOnce(() => {});
        const first = await preparePattern('s("bd"', { load });
        expect(first).toMatchObject({ ok: false, unavailable: true, code: 's("bd"' });
        expect(first.error).toMatch(/Reload the page/);
        expect(await preparePattern('s("bd")', { load })).toEqual({ ok: true, code: 's("bd")', repaired: false, error: null });
        expect(load).toHaveBeenCalledTimes(2);
    });
});

describe('preparePattern', () => {
    it('returns valid code exactly as it is, even with typographic characters in strings and comments', async () => {
        const code = 'const label = "He said “hi”"; s("A–B") // it’s — fine';
        expect(await preparePattern(code)).toEqual({ ok: true, code, repaired: false, error: null });
    });

    it('repairs curly quotes used as string delimiters, and says so', async () => {
        expect(await preparePattern('s(“bd sd”).bank(‘RolandTR909’)')).toEqual({ ok: true, code: 's("bd sd").bank(\'RolandTR909\')', repaired: true, error: null });
    });

    it('refuses code that does not parse even after repair, with the error of the original', async () => {
        const result = await preparePattern('s("bd sd"');
        expect(result).toMatchObject({ ok: false, code: 's("bd sd"', repaired: false });
        expect(result.error).toMatch(/Unexpected token/);
    });

    it('the code it returns is the code that is validated: it always parses when ok', async () => {
        for (const input of ['s(“bd”)', 'note(“c e g”).gain(1 – 0.5)', '$: s("hh*8")']) {
            const { ok, code } = await preparePattern(input);
            expect(ok).toBe(true);
            expect(await patternSyntaxError(code)).toBeNull();
        }
    });
});
