import { describe, expect, it } from 'vitest';
import { patternSyntaxError } from './patternCheck';

describe('patternSyntaxError', () => {
    it('accepts the forms Strudel code uses', async () => {
        const valid = [
            's("bd sd hh sd")',
            '$: s("bd*4")\n$: note("c2 g2").s("sawtooth")', // several $: labels
            'await initHydra()\nosc(10, 0.1, 1.2).out()\n$: s("bd sd")', // top-level await
            'await initHydra({detectAudio: true})\nlet pattern = "3 4 5 [6 7]*2"\nshape(H(pattern)).out(o0)\nnote(pattern).s("piano")',
            'setcpm(120/4)\nstack(\n  s("bd(3,8), sd(5,8)"),\n  note(`<[c3,e3,g3] [a2,c3,e3]>`).s("piano").room(0.5)\n)',
            '// Generated by Model X via https://ronnqvist.github.io/strudel-vibe-coder/\n// ä ö å € 🎵\ns("bd").every(4, x => x.fast(2))',
        ];
        for (const code of valid) expect(await patternSyntaxError(code), code).toBeNull();
    });

    it('refuses code that does not parse, with the parser message and position', async () => {
        expect(await patternSyntaxError('s("bd sd"')).toMatch(/Unexpected token \(1:9\)/);
        expect(await patternSyntaxError('stack(\n  s("bd"),\n  note("c e g"))\n)')).toMatch(/\(4:0\)/);
        expect(await patternSyntaxError('s(“bd”)')).toMatch(/Unexpected character/); // smart quotes
    });

    it('lets empty input through (nothing to load)', async () => {
        expect(await patternSyntaxError('')).toBeNull();
        expect(await patternSyntaxError('   \n')).toBeNull();
        expect(await patternSyntaxError(undefined)).toBeNull();
    });

    it('fails open when the parser breaks in a way that is not a syntax error', async () => {
        const broken = () => { throw new TypeError('parser bug'); };
        expect(await patternSyntaxError('s("bd")', { parse: broken })).toBeNull();
    });
});
